"""Sistema de espaciado consistente."""

class Spacing:
    """Espaciados estandarizados del sistema."""
    
    # Espaciados base
    XS = 4
    SM = 8
    MD = 16
    LG = 24
    XL = 32
    
    # Padding para elementos específicos
    CARD_PADDING = 24
    PANEL_PADDING = 32
    BUTTON_PADDING = (14, 24)  # (vertical, horizontal)
    
    # Gaps entre elementos
    FORM_GAP = 20
    ELEMENT_GAP = 16
    
    # Border Radius
    RADIUS_SM = 6
    RADIUS_MD = 8
    RADIUS_LG = 12
